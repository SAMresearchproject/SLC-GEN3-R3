def now_utc() -> str:
    return datetime.now(timezone.utc).isoformat()


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def write_json(path: Path, obj: object) -> None:
    path.write_text(json.dumps(obj, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def fraction_text(value: Fraction) -> str:
    if value.denominator == 1:
        return str(value.numerator)
    return f"{value.numerator}/{value.denominator}"


def decimal_text(value: Fraction, places: int = 48) -> str:
    dec = Decimal(value.numerator) / Decimal(value.denominator)
    s = format(dec, f".{places}f")
    if "." in s:
        s = s.rstrip("0").rstrip(".")
    return s or "0"


def exponents_for_partition(p: int) -> tuple[int, int]:
    n = p
    a = 0
    while n % ALPHA_H == 0:
        a += 1
        n //= ALPHA_H
    b = 0
    while n % D == 0:
        b += 1
        n //= D
    if n != 1:
        raise ValueError(f"partition {p} is not generated by alpha_H={ALPHA_H} and D={D}")
    return a, b


def selector_rule_for(p: int, depth: int) -> str:
    if depth in (0, 1):
        return "DEPTH_0_1_ALL_PARTITION_MODES"
    if depth == 2 and p in DEPTH_PARTITIONS[2]:
        return "DEPTH_2_LOW_PARTITION_MODES_ONLY"
    return "FORBIDDEN_BY_NATIVE_SELECTOR"


def row_hash(payload: dict[str, str]) -> str:
    keys = [
        "partition_mode",
        "generator_exponents",
        "depth",
        "charge_sign",
        "charge_magnitude",
        "operator_class",
        "native_mass_fraction",
        "source_support",
        "tensor_support",
        "retained_support",
        "selector_rule",
    ]
    material = {
        "constants": {"alpha_H": ALPHA_H, "D": D, "R": R},
        "row": {k: payload[k] for k in keys},
        "generator": TEST_ID,
    }
    return hashlib.sha256(json.dumps(material, sort_keys=True).encode("utf-8")).hexdigest()


def build_native_rows(
    depth_partitions: dict[int, tuple[int, ...]] | None = None,
    charge_states: tuple[tuple[str, int, str, str, Fraction], ...] = CHARGE_STATES,
) -> list[dict[str, str]]:
    depth_partitions = depth_partitions or DEPTH_PARTITIONS
    rows: list[dict[str, str]] = []
    ordinal = 1
    for depth in sorted(depth_partitions):
        for p in depth_partitions[depth]:
            a, b = exponents_for_partition(p)
            for charge_sign, charge_int, operator_class, route_class, mass_factor in charge_states:
                mass = Fraction(p, 1) * (R ** depth) * mass_factor
                charge_magnitude = 0 if charge_sign == "neutral" else p
                if charge_sign == "neutral":
                    source = mass
                else:
                    source = mass * Fraction(R * R + 1, R * R)
                tensor = source / (2 ** D)
                retained = source - tensor
                row = {
                    "native_id": f"SAMN63-{ordinal:04d}",
                    "partition_mode": str(p),
                    "generator_exponents": f"alpha_H^{a}*D^{b}",
                    "generator_exponent_alphaH": str(a),
                    "generator_exponent_D": str(b),
                    "depth": str(depth),
                    "charge_sign": charge_sign,
                    "charge_magnitude": str(charge_magnitude),
                    "native_charge_axis": {
                        "neutral": "neutral",
                        "positive": "plus",
                        "negative": "minus",
                    }[charge_sign],
                    "operator_class": operator_class,
                    "route_class": route_class,
                    "native_mass_or_weight": decimal_text(mass, places=24),
                    "native_mass_fraction": fraction_text(mass),
                    "source_support": fraction_text(source),
                    "source_support_decimal": decimal_text(source),
                    "tensor_support": fraction_text(tensor),
                    "tensor_support_decimal": decimal_text(tensor),
                    "retained_support": fraction_text(retained),
                    "retained_support_decimal": decimal_text(retained),
                    "selector_rule": selector_rule_for(p, depth),
                    "address_signature": f"p={p}|d={depth}|q={charge_sign}:{charge_magnitude}",
                    "route_combination": f"{charge_sign}_single_write[p={p},g={depth}]",
                    "construction_hash": "",
                }
                row["construction_hash"] = row_hash(row)
                rows.append(row)
                ordinal += 1
    return rows


def render_csv(rows: Iterable[dict[str, str]], fields: list[str]) -> bytes:
    from io import StringIO

    buf = StringIO()
    writer = csv.DictWriter(buf, fieldnames=fields, lineterminator="\n")
    writer.writeheader()
    for row in rows:
        writer.writerow({field: row.get(field, "") for field in fields})
    return buf.getvalue().encode("utf-8")


def write_csv(path: Path, rows: Iterable[dict[str, str]], fields: list[str]) -> None:
    path.write_bytes(render_csv(rows, fields))


def address_key(row: dict[str, str]) -> tuple[int, int, str]:
    return (int(row["partition_mode"]), int(row["depth"]), row["charge_sign"])


def cr219_address_key(row: dict[str, str]) -> tuple[int, int, str]:
    return (
        int(row["partition_signature"]),
        int(row["closure_depth"]),
        row["q_sign"],
    )


def read_cr219_stable_rows() -> list[dict[str, str]]:
    with CR219_PROMOTED.open("r", encoding="utf-8", newline="") as f:
        rows = [
            row for row in csv.DictReader(f)
            if row.get("bin") == "stable_matter_rows"
        ]
    return rows


def validation_rows(native_rows: list[dict[str, str]], cr219_rows: list[dict[str, str]]) -> list[dict[str, str]]:
    generated = {address_key(row): row for row in native_rows}
    source = {cr219_address_key(row): row for row in cr219_rows}
    all_keys = sorted(set(generated) | set(source))
    rows = []
    for key in all_keys:
        g = generated.get(key)
        s = source.get(key)
        generated_mass = Fraction(g["native_mass_fraction"]) if g else None
        source_mass = Fraction(s["M_native"]) if s else None
        operator_match = bool(g and s and g["operator_class"] == s["operator_class"])
        mass_match = bool(g and s and generated_mass == source_mass)
        rows.append({
            "partition_mode": str(key[0]),
            "depth": str(key[1]),
            "charge_sign": key[2],
            "generated_native_id": g["native_id"] if g else "",
            "cr219_candidate_id": s["candidate_id"] if s else "",
            "signature_in_generated": str(g is not None),
            "signature_in_cr219": str(s is not None),
            "operator_match": str(operator_match),
            "native_mass_match": str(mass_match),
            "generated_operator_class": g["operator_class"] if g else "",
            "cr219_operator_class": s["operator_class"] if s else "",
            "generated_native_mass_fraction": g["native_mass_fraction"] if g else "",
            "cr219_M_native": s["M_native"] if s else "",
            "used_as_construction_input": "no",
        })
    return rows


def check_duplicate_repair_failure(rows: list[dict[str, str]]) -> bool:
    repaired = [dict(r) for r in rows]
    repaired[0] = dict(repaired[1])
    keys = [(r["partition_mode"], r["depth"], r["charge_sign"]) for r in repaired]
    return len(repaired) == 63 and len(set(keys)) != 63


def build_checks(native_rows: list[dict[str, str]], validation: list[dict[str, str]]) -> list[Check]:
    depth_counts: dict[str, int] = {}
    for row in native_rows:
        depth_counts[row["depth"]] = depth_counts.get(row["depth"], 0) + 1
    address_keys = [(r["partition_mode"], r["depth"], r["charge_sign"]) for r in native_rows]
    forbidden_d2 = [
        r["partition_mode"] for r in native_rows
        if r["depth"] == "2" and r["partition_mode"] in {"8", "9", "12"}
    ]
    labels_present = [
        key for row in native_rows
        for key, value in row.items()
        if key in {"known_name", "known_symbol", "known_label", "candidate_id"} and value
    ]
    all_validation_matches = all(
        row["signature_in_generated"] == "True"
        and row["signature_in_cr219"] == "True"
        and row["operator_match"] == "True"
        and row["native_mass_match"] == "True"
        for row in validation
    )
    full_depth2 = dict(DEPTH_PARTITIONS)
    full_depth2[2] = PARTITION_MODES
    wrong_72 = build_native_rows(depth_partitions=full_depth2)
    wrong_two_charges = build_native_rows(charge_states=CHARGE_STATES[:2])
    rendered_1 = render_csv(native_rows, CSV_FIELDS)
    rendered_2 = render_csv(build_native_rows(), CSV_FIELDS)

    return [
        Check("native_rows_exactly_63", len(native_rows) == 63, str(len(native_rows)), "63"),
        Check("depth_counts_24_24_15", depth_counts == {"0": 24, "1": 24, "2": 15}, str(depth_counts), "{'0': 24, '1': 24, '2': 15}"),
        Check("addresses_unique_63", len(set(address_keys)) == 63, str(len(set(address_keys))), "63"),
        Check("forbidden_depth2_modes_absent", not forbidden_d2, ",".join(forbidden_d2), "none"),
        Check("known_labels_absent_from_construction_fields", not labels_present, str(labels_present), "[]"),
        Check("deterministic_byte_identical_regeneration", rendered_1 == rendered_2, sha256_bytes(rendered_1), sha256_bytes(rendered_2)),
        Check("wrong_control_depth2_full_modes_produces_72", len(wrong_72) == 72, str(len(wrong_72)), "72"),
        Check("wrong_control_removed_charge_state_breaks_count", len(wrong_two_charges) != 63, str(len(wrong_two_charges)), "not 63"),
        Check("wrong_control_duplicate_repair_fails_uniqueness", check_duplicate_repair_failure(native_rows), "duplicate_repaired_count_63_unique_lt_63", "detected"),
        Check("downstream_cr219_validation_63_signatures_mass_operator", all_validation_matches, str(sum(1 for row in validation if row['native_mass_match'] == 'True')), "63"),
    ]


def write_hashes(paths: list[Path]) -> None:
    lines = []
    for path in sorted(paths, key=lambda p: p.name):
        lines.append(f"{sha256_file(path)}  {path.name}")
    OUT_HASHES.write_text("\n".join(lines) + "\n", encoding="ascii")


def write_precommit(native_rows_sha: str) -> None:
    text = f"""# CR220 PRECOMMIT - Native 63 Generator

## Scope

Generate `Tier1_Native63.csv` from SAM constants only:

```text
alpha_H = {ALPHA_H}
D = {D}
R = {R}
Pi = {PARTITION_MODES}
charges = neutral, positive, negative
```

## Generator

Depths 0 and 1 admit all eight partition modes. Depth 2 admits only
`1, 2, 3, 4, 6`. For every allowed `(p,d)`, emit the neutral, positive,
negative triplet.

Native mass:

```text
M_native = p * R^d * k
neutral  k = 1/8
positive k = 5/4
negative k = 3/2
```

Charged source support uses the first carrier lift:

```text
source_support(charged) = M_native * (R^2 + 1) / R^2
source_support(neutral) = M_native
tensor_support          = source_support / 2^D
retained_support        = source_support - tensor_support
```

## Source Boundary

`CR219_promoted_particle_rows_126.csv` is read only after generation as a
downstream validation surface. It supplies no candidate IDs, names, labels, or
rows to the construction step.

## Pre-run Hash

Expected generated CSV hash after deterministic construction:

```text
{native_rows_sha}
```
"""
    OUT_PRECOMMIT.write_text(text, encoding="utf-8")


