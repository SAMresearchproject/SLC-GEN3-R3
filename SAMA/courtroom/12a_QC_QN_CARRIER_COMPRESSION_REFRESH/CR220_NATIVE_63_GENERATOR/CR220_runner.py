def main() -> int:
    CR_DIR.mkdir(parents=True, exist_ok=True)

    native_rows = build_native_rows()
    native_csv_bytes = render_csv(native_rows, CSV_FIELDS)
    native_sha = sha256_bytes(native_csv_bytes)
    OUT_NATIVE.write_bytes(native_csv_bytes)

    cr219_rows = read_cr219_stable_rows()
    validation_source_fields = [
        "candidate_id",
        "bin",
        "route_combination",
        "operator_class",
        "partition_signature",
        "closure_depth",
        "q_sign",
        "q_abs",
        "M_native",
        "known_identity_label",
        "known_symbol",
        "known_name",
        "known_label_used_as_construction_input",
    ]
    write_csv(OUT_VALIDATION_SOURCE, cr219_rows, validation_source_fields)

    validation = validation_rows(native_rows, cr219_rows)
    validation_fields = [
        "partition_mode",
        "depth",
        "charge_sign",
        "generated_native_id",
        "cr219_candidate_id",
        "signature_in_generated",
        "signature_in_cr219",
        "operator_match",
        "native_mass_match",
        "generated_operator_class",
        "cr219_operator_class",
        "generated_native_mass_fraction",
        "cr219_M_native",
        "used_as_construction_input",
    ]
    write_csv(OUT_VALIDATION, validation, validation_fields)

    checks = build_checks(native_rows, validation)
    write_csv(OUT_CHECKS, [asdict(check) for check in checks], ["check", "passed", "observed", "expected"])

    checks_passed = sum(1 for check in checks if check.passed)
    checks_total = len(checks)
    result_class = (
        "CR220_PASS_NATIVE_63_GENERATOR__CONSTANTS_ONLY__24_24_15__"
        "DOWNSTREAM_CR219_SIGNATURE_MATCH"
        if checks_passed == checks_total
        else "CR220_FAIL_NATIVE_63_GENERATOR"
    )

    summary = {
        "cr_id": CR_ID,
        "test_id": TEST_ID,
        "execution_status": "CLEAN",
        "generated_at_utc": now_utc(),
        "result_class": result_class,
        "checks_passed": checks_passed,
        "checks_total": checks_total,
        "constants": {"alpha_H": ALPHA_H, "D": D, "R": R},
        "partition_modes": list(PARTITION_MODES),
        "depth_partitions": {str(k): list(v) for k, v in DEPTH_PARTITIONS.items()},
        "charge_order": [c[0] for c in CHARGE_STATES],
        "row_count": len(native_rows),
        "depth_counts": {
            str(depth): sum(1 for row in native_rows if row["depth"] == str(depth))
            for depth in sorted(DEPTH_PARTITIONS)
        },
        "source_boundary": "CR219 read after generation as downstream validation only; no imported IDs or labels in construction.",
        "roadmap": str(ROADMAP.relative_to(COURTROOM_DIR)),
        "validation_source": str(CR219_PROMOTED.relative_to(COURTROOM_DIR)),
        "outputs": {
            "native_csv": OUT_NATIVE.name,
            "validation_source_csv": OUT_VALIDATION_SOURCE.name,
            "validation_csv": OUT_VALIDATION.name,
            "checks_csv": OUT_CHECKS.name,
            "summary_json": OUT_SUMMARY.name,
            "result_md": OUT_RESULT.name,
        },
        "sha256": {
            "Tier1_Native63.csv": native_sha,
        },
        "next_gate": "CR221_BOUND_63_GENERATOR",
    }

    write_precommit(native_sha)
    write_readme()
    write_json(OUT_SUMMARY, summary)
    write_result(summary)
    write_hashes([
        OUT_NATIVE,
        OUT_VALIDATION_SOURCE,
        OUT_VALIDATION,
        OUT_CHECKS,
        OUT_PRECOMMIT,
        OUT_SUMMARY,
        OUT_RESULT,
        OUT_README,
    ])

    print("CR220 native 63 generator complete")
    print(f"  result_class: {result_class}")
    print(f"  checks: {checks_passed}/{checks_total}")
    print(f"  rows: {len(native_rows)}")
    print(f"  Tier1_Native63.csv sha256: {native_sha}")
    return 0 if checks_passed == checks_total else 1


if __name__ == "__main__":
    raise SystemExit(main())
